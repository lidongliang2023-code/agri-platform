-- ------------------------------------------------ V20 补齐演示农场 + 重播食品安全风险评分
--
-- 为什么单独开 V20 而不是改 V19：
--   V19 已经应用到开发库，Flyway 会做**校验和校验**。改 V19 的文件内容会让
--   `Validate failed: Migration checksum mismatch for migration version 19` 在启动时抛出，
--   应用直接起不来（V15 的注释里记过同一个坑）。已应用的迁移一律不再编辑 —— 这是硬规矩。
--
-- 解决两个问题：
--   1) P15 食品安全风险热力图是 4×4=16 格，但库内只有 DEMO-FARM-001~006 共 6 个演示农场，
--      实测接口只返回 6 条、热力图缺 10 格。按用户裁决**补 10 个演示农场**（007~016），
--      全部 status=1 启用，与既有 6 个农场字段口径完全一致（farm_code 走 DEMO-FARMC-00N）。
--   2) 风险评分随之重播为 16 个农场 × 2 个统计月 = 32 行，配色覆盖绿 11 / 黄 3 / 红 2。
--
-- ⚠️ 口径已知取舍（需产品确认）：DEMO-FARM-006 是**停用**农场（status=0，
--   原种子里专用于验证列表状态筛选）。本次仍为它保留评分（48 分，最低，红格）——
--   风险台账不因农场停用而抹掉历史评分。若产品要求热力图只统计启用农场，
--   在 AdminFoodSafetyMonitorService#riskDistribution 加一层 status=1 过滤即可，
--   届时热力图会变成 15 格。
--
-- 指标口径（与 V19 注释一致，全部由明细实时聚合）：
--   当期(2026-10) 16 农场均值 = 1333/16 = 83.3；上期(2026-09) = 1296/16 = 81.0；
--   故 safetyIndex = 83.3、safetyIndexDelta = +2.3。
--
-- 幂等：农场用 ON DUPLICATE KEY UPDATE（farm_code 有唯一键），风险评分先按
--   DEMO-FS-RISK-% 前缀 DELETE 再插入，不触碰任何非演示数据。

