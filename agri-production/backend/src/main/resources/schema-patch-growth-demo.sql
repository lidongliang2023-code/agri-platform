-- 补丁：生长监测演示数据（**可重复执行**：逐行显式主键 + INSERT IGNORE）。
-- 跑法：mysql -uroot -p --default-character-set=utf8mb4 agri_production < schema-patch-growth-demo.sql
--
-- 内容由 agri_core.prod_growth_record 的 10 条演示行**机械转换**而来（脚本生成，非手抄）：
--   · record_id / plot_id / plan_id / crop_id / growth_stage / record_date / weather / photos /
--     recorder_id / remark / status 照抄；height → plant_height，leaf_count、pest_level 照抄；
--   · plot_name 由 prod_plot_info 联查、recorder_name 由 prod_member 联查得到；
--   · farm_id 由平台农场标识经本库 agri_prod_farm_info.platform_farm_id 换算成本地主键。
--
-- 【哪三列是推算值而不是记录值】
-- 页面契约要求 growth_level / leaf_area_index / pest_info 三列，而平台演示行里没有这三个字段，
-- 所以按固定规则推出来 —— 接口里**没有**这套算法（免得把算出来的长期当成记下来的），
-- 上线后这三列由人工录入：
--   · growth_level：pest_level >= 2 → 2 偏弱；pest_level = 1 或 叶数 < 10 → 3 正常；其余 → 4 旺盛；
--   · leaf_area_index：叶数 ÷ 10，保留 1 位小数；叶数为空的行留空；
--   · pest_info：仅 pest_level >= 2 的行取 remark 整段，其余留空。
--     另一种读法是「按关键词从 remark 里抽病害短语」，这里刻意没走：pest_level = 1 的几行备注是
--     「注意观察是否有病害」「生长整齐，无病害」这类**观望句/否定句**，抽出来当病虫害描述展示会失真。
--     代价是 pest_level = 1 且备注里确实提到病害的行（如「抽穗整齐，稻瘟病零星发生」）pest_info 为空，
--     remark 仍保留原文可供人看 —— 宁可少展示，不把观望句当结论。
--   · crop_name 留空：平台侧没有作物主数据表（无 prod_crop_info），机械转换取不到作物名。
--     页面「作物」列显示 -，这与切换前的平台侧表现一致（那边的实体也没有作物名列）。
--
-- 【已知的口径不一致】平台演示数据的生育期用词是 苗期/花期/果期/成熟期/分蘖期/抽穗期，
-- 而页面下拉选项是 苗期/开花期/结果期/采收期（GrowthRecords.tsx 的 STAGE_OPTIONS）。
-- 这里**照抄原文**，不替产品做同义改写：改名的代价是页面上按「开花期」筛选筛不到「花期」记录，
-- 而随手动改的代价是数据与平台侧对不上、以后没人知道哪边是原话。属遗留，待产品统一用词。
--
-- 【演示环境读数】库内 agri_prod_sensor_data 原本只有 1 个地块 3 个时点的温度。
-- 这里按 1 个地块 × 3 天 × 3 个时点 × 4 个指标补齐，让环境数据页与趋势曲线真的有数可看。
-- 数值是按时间槽位固定算式生成的**演示读数**（温度 22.4/27.6/25.1 起、湿度 61.0/52.4/66.3 起、
-- 土壤湿度 38.2/35.6/33.1 起、光照 24500/48600/12800 起，逐日小幅偏移），不是真实采集。
-- 2026-10-13 的温度刻意不补：该日 08/12/16 三条温度读数（id 1~3）库里已有。
-- 现有读数只覆盖 temperature / humidity / soil_moisture / illuminance 四类，
-- 因此宽表里的 soil_temperature / co2 / rainfall 三列就是 null（页面显示 -，表示未接入该类传感器）。
--
-- 演示基线复位：跑完探针把被改动过的行还原为 update_time = create_time。

